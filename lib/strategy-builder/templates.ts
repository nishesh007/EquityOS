export function getTemplateById(id: string | null | undefined): StrategyTemplate | null {
  if (!id) return null;
  return STRATEGY_TEMPLATES.find((t) => t.id === id) ?? null;
}

export function cloneTemplate(template: StrategyTemplate): StrategyTemplate {
  return {
    ...template,
    tags: [...template.tags],
    blocks: {
      ...template.blocks,
      technicalIndicators: [...template.blocks.technicalIndicators],
      fundamentalFilters: [...template.blocks.fundamentalFilters],
      valuationFilters: [...template.blocks.valuationFilters],
      volumeFilters: [...template.blocks.volumeFilters],
      momentumFilters: [...template.blocks.momentumFilters],
      riskRules: [...template.blocks.riskRules],
      exitRules: [...template.blocks.exitRules],
    },
    rules: {
      ...template.rules,
      entry: [...template.rules.entry],
      exit: [...template.rules.exit],
      riskRules: [...template.rules.riskRules],
      marketFilters: [...template.rules.marketFilters],
      sectorFilters: [...template.rules.sectorFilters],
      liquidityFilters: [...template.rules.liquidityFilters],
    },
  };
}
