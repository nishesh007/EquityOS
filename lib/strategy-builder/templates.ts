import type { StrategyBuildingBlocks, StrategyRules, StrategyTemplate } from "./types";

function blocks(
  partial: Partial<StrategyBuildingBlocks> &
    Pick<StrategyBuildingBlocks, "universe" | "marketRegime" | "positionSizing" | "holdingPeriod">
): StrategyBuildingBlocks {
  return {
    technicalIndicators: partial.technicalIndicators ?? [],
    fundamentalFilters: partial.fundamentalFilters ?? [],
    valuationFilters: partial.valuationFilters ?? [],
    volumeFilters: partial.volumeFilters ?? [],
    momentumFilters: partial.momentumFilters ?? [],
    riskRules: partial.riskRules ?? ["Max risk 1% per trade"],
    exitRules: partial.exitRules ?? ["Target or stop"],
    positionSizing: partial.positionSizing,
    holdingPeriod: partial.holdingPeriod,
    universe: partial.universe,
    marketRegime: partial.marketRegime,
  };
}

function rules(partial: Partial<StrategyRules>): StrategyRules {
  return {
    entry: partial.entry ?? [],
    exit: partial.exit ?? [],
    stopLossPct: partial.stopLossPct ?? 4,
    targetPct: partial.targetPct ?? 8,
    trailingStopPct: partial.trailingStopPct ?? null,
    positionSizePct: partial.positionSizePct ?? 5,
    holdingMinDays: partial.holdingMinDays ?? 3,
    holdingMaxDays: partial.holdingMaxDays ?? 20,
    riskRules: partial.riskRules ?? ["Risk ≤ 1% equity per idea"],
    marketFilters: partial.marketFilters ?? [],
    sectorFilters: partial.sectorFilters ?? [],
    liquidityFilters: partial.liquidityFilters ?? ["ADV ≥ ₹5 Cr"],
  };
}

